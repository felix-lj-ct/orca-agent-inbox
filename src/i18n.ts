export function strings(language: Language, orcaLocale: string): Strings {
  const resolved = language === 'auto' ? (orcaLocale.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en') : language
  return resolved === 'zh-CN' ? zhCN : en
}
